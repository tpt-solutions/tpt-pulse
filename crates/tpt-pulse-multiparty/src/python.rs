//! Python stubs for a protocol.
//!
//! The output mirrors [`crate::typescript_stubs`]: one `TypedDict` per message
//! label, built from its JSON Schema, and each role's projected program as a typed
//! list. The message types use functional `TypedDict` syntax, so keys such as
//! `from` can be used as they are. Requires Python 3.11 or later, for `NotRequired`.

use serde_json::{Map, Value};

use crate::schema::collect_labels;
use crate::{Action, GlobalProtocol, Schemas, StubError};

const PREAMBLE: &str = r#"# Generated by tpt-pulse-multiparty. Do not edit.
#
# `Op` is one step of a role's projected program. Choices and loops are nested
# as the protocol has them. `choose` announces a branch, and `offer` waits for one.
# Requires Python 3.11 or later.

from typing import Any, Dict, List, Literal, NotRequired, Optional, TypedDict, Union

Send = TypedDict("Send", {"op": Literal["send"], "to": str, "label": str})
Recv = TypedDict("Recv", {"op": Literal["recv"], "from": str, "label": str})
Choose = TypedDict(
    "Choose", {"op": Literal["choose"], "to": List[str], "branches": List[List["Op"]]}
)
Offer = TypedDict(
    "Offer", {"op": Literal["offer"], "from": str, "branches": List[List["Op"]]}
)
Loop = TypedDict("Loop", {"op": Literal["loop"], "body": List["Op"]})
Continue = TypedDict("Continue", {"op": Literal["continue"]})
Op = Union[Send, Recv, Choose, Offer, Loop, Continue]
"#;

/// Python for the whole protocol: message types, then one program per role.
pub fn python_stubs(protocol: &GlobalProtocol, schemas: &Schemas) -> Result<String, StubError> {
    let missing = schemas.missing(protocol);
    if !missing.is_empty() {
        return Err(StubError::MissingSchemas(missing));
    }
    let session = protocol.project().map_err(StubError::Protocol)?;

    let mut labels = Vec::new();
    collect_labels(protocol.statements(), &mut labels);

    let mut out = String::from(PREAMBLE);
    out.push('\n');
    for label in &labels {
        let schema = schemas.get(label).expect("missing schemas were rejected");
        out.push_str(&message_types(label, schema));
    }

    out.push_str("Messages = TypedDict(\"Messages\", {");
    let fields: Vec<String> = labels
        .iter()
        .map(|label| format!("{}: {}", quoted(label), ident(label)))
        .collect();
    out.push_str(&fields.join(", "));
    out.push_str("})\n");

    for program in session.programs() {
        let mut literal = String::new();
        action_list(&program.actions, &mut literal);
        out.push_str(&format!(
            "\n{}Program: List[Op] = {literal}\n",
            ident(&program.role)
        ));
    }
    Ok(out)
}

/// The definitions of one message, then the message itself.
fn message_types(label: &str, schema: &Value) -> String {
    let mut out = String::new();
    let defs = schema
        .get("$defs")
        .or_else(|| schema.get("definitions"))
        .and_then(Value::as_object);
    if let Some(defs) = defs {
        for (name, def) in defs {
            out.push_str(&format!(
                "{} = {}\n",
                def_name(label, name),
                named(def, &def_name(label, name), label)
            ));
        }
    }
    let name = ident(label);
    out.push_str(&format!("{name} = {}\n", named(schema, &name, label)));
    out
}

/// A definition's type. An object with fields becomes a named `TypedDict`.
fn named(schema: &Value, name: &str, label: &str) -> String {
    match schema.as_object() {
        Some(map) if is_object(map) => {
            let required: Vec<&str> = map
                .get("required")
                .and_then(Value::as_array)
                .map(|names| names.iter().filter_map(Value::as_str).collect())
                .unwrap_or_default();
            let fields: Vec<String> = map
                .get("properties")
                .and_then(Value::as_object)
                .into_iter()
                .flatten()
                .map(|(field, field_schema)| {
                    let kind = expr(field_schema, label);
                    let kind = if required.contains(&field.as_str()) {
                        kind
                    } else {
                        format!("NotRequired[{kind}]")
                    };
                    format!("{}: {kind}", quoted(field))
                })
                .collect();
            format!("TypedDict({}, {{{}}})", quoted(name), fields.join(", "))
        }
        _ => expr(schema, label),
    }
}

/// Whether a schema describes an object with named fields.
fn is_object(map: &Map<String, Value>) -> bool {
    map.get("properties").and_then(Value::as_object).is_some()
        && !map.contains_key("anyOf")
        && !map.contains_key("oneOf")
}

/// The Python type for a JSON Schema. Unsupported keywords become `Any`.
fn expr(schema: &Value, label: &str) -> String {
    match schema {
        Value::Bool(_) => "Any".into(),
        Value::Object(map) => {
            if let Some(reference) = map.get("$ref").and_then(Value::as_str) {
                let name = reference
                    .strip_prefix("#/$defs/")
                    .or_else(|| reference.strip_prefix("#/definitions/"));
                return name.map_or("Any".into(), |name| def_name(label, name));
            }
            if let Some(constant) = map.get("const") {
                return format!("Literal[{}]", literal(constant));
            }
            if let Some(values) = map.get("enum").and_then(Value::as_array) {
                let values: Vec<String> = values.iter().map(literal).collect();
                return format!("Literal[{}]", values.join(", "));
            }
            for keyword in ["anyOf", "oneOf"] {
                if let Some(options) = map.get(keyword).and_then(Value::as_array) {
                    return union(options.iter().map(|option| expr(option, label)));
                }
            }
            match map.get("type") {
                Some(Value::String(kind)) => by_type(kind, map, label),
                Some(Value::Array(kinds)) => union(
                    kinds
                        .iter()
                        .filter_map(Value::as_str)
                        .map(|kind| by_type(kind, map, label)),
                ),
                _ if map.contains_key("properties") => "Dict[str, Any]".into(),
                _ => "Any".into(),
            }
        }
        _ => "Any".into(),
    }
}

fn by_type(kind: &str, map: &Map<String, Value>, label: &str) -> String {
    match kind {
        "string" => "str".into(),
        "integer" => "int".into(),
        "number" => "float".into(),
        "boolean" => "bool".into(),
        "null" => "None".into(),
        "array" => match map.get("items") {
            Some(items) => format!("List[{}]", expr(items, label)),
            None => "List[Any]".into(),
        },
        "object" => match map.get("additionalProperties") {
            Some(extra @ Value::Object(_)) => format!("Dict[str, {}]", expr(extra, label)),
            _ => "Dict[str, Any]".into(),
        },
        _ => "Any".into(),
    }
}

/// A union of distinct types, with `Optional` for a union with `None`.
fn union(parts: impl Iterator<Item = String>) -> String {
    let mut unique: Vec<String> = Vec::new();
    for part in parts {
        if !unique.contains(&part) {
            unique.push(part);
        }
    }
    match unique.as_slice() {
        [] => "Any".into(),
        [only] => only.clone(),
        [first, second] if second == "None" => format!("Optional[{first}]"),
        _ => format!("Union[{}]", unique.join(", ")),
    }
}

/// A JSON scalar as a Python literal.
fn literal(value: &Value) -> String {
    match value {
        Value::Bool(true) => "True".into(),
        Value::Bool(false) => "False".into(),
        Value::Null => "None".into(),
        Value::String(text) => quoted(text),
        other => other.to_string(),
    }
}

/// A string as a double-quoted Python literal. JSON string syntax is valid Python.
fn quoted(text: &str) -> String {
    serde_json::to_string(text).expect("a string serializes")
}

/// The name of a definition inside a message's schema.
fn def_name(label: &str, name: &str) -> String {
    ident(&format!("{label}_{name}"))
}

/// A name that is a valid, non-keyword Python identifier.
fn ident(name: &str) -> String {
    const KEYWORDS: [&str; 35] = [
        "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class",
        "continue", "def", "del", "elif", "else", "except", "finally", "for", "from", "global",
        "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return",
        "try", "while", "with", "yield",
    ];
    let mut out: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    if KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

/// The program for a list of actions, as a Python list literal.
fn action_list(actions: &[Action], out: &mut String) {
    out.push('[');
    for (index, action) in actions.iter().enumerate() {
        if index > 0 {
            out.push_str(", ");
        }
        action_value(action, out);
    }
    out.push(']');
}

fn action_value(action: &Action, out: &mut String) {
    match action {
        Action::Send { to, label } => out.push_str(&format!(
            "{{\"op\": \"send\", \"to\": {}, \"label\": {}}}",
            quoted(to),
            quoted(label)
        )),
        Action::Recv { from, label } => out.push_str(&format!(
            "{{\"op\": \"recv\", \"from\": {}, \"label\": {}}}",
            quoted(from),
            quoted(label)
        )),
        Action::Choose { to, branches } => {
            let roles: Vec<String> = to.iter().map(|role| quoted(role)).collect();
            out.push_str(&format!(
                "{{\"op\": \"choose\", \"to\": [{}], \"branches\": ",
                roles.join(", ")
            ));
            branch_list(branches, out);
            out.push('}');
        }
        Action::Offer { from, branches } => {
            out.push_str(&format!(
                "{{\"op\": \"offer\", \"from\": {}, \"branches\": ",
                quoted(from)
            ));
            branch_list(branches, out);
            out.push('}');
        }
        Action::Loop(body) => {
            out.push_str("{\"op\": \"loop\", \"body\": ");
            action_list(body, out);
            out.push('}');
        }
        Action::Continue => out.push_str("{\"op\": \"continue\"}"),
    }
}

fn branch_list(branches: &[Vec<Action>], out: &mut String) {
    out.push('[');
    for (index, branch) in branches.iter().enumerate() {
        if index > 0 {
            out.push_str(", ");
        }
        action_list(branch, out);
    }
    out.push(']');
}
