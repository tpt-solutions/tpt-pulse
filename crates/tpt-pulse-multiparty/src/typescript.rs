//! TypeScript stubs for a protocol.
//!
//! The output has one type per message label, built from its JSON Schema. It also
//! has each role's projected program as a typed constant, with choices and loops
//! nested as the protocol has them. A runtime can interpret those constants.

use std::fmt;

use serde_json::{Map, Value};

use crate::schema::collect_labels;
use crate::{Action, GlobalProtocol, ProtocolError, Schemas};

/// Why stubs could not be generated.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum StubError {
    /// Some labels the protocol sends have no schema.
    MissingSchemas(Vec<String>),
    /// The protocol is not well formed.
    Protocol(ProtocolError),
}

impl fmt::Display for StubError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::MissingSchemas(labels) => {
                write!(f, "no schema for message(s): {}", labels.join(", "))
            }
            Self::Protocol(error) => write!(f, "{error}"),
        }
    }
}

impl std::error::Error for StubError {}

const PREAMBLE: &str = "// Generated by tpt-pulse-multiparty. Do not edit.
//
// `Op` is one step of a role's projected program. Choices and loops are nested
// as the protocol has them. `choose` announces a branch, and `offer` waits for one.

export type Op =
  | { op: \"send\"; to: string; label: string }
  | { op: \"recv\"; from: string; label: string }
  | { op: \"choose\"; to: readonly string[]; branches: readonly (readonly Op[])[] }
  | { op: \"offer\"; from: string; branches: readonly (readonly Op[])[] }
  | { op: \"loop\"; body: readonly Op[] }
  | { op: \"continue\" };
";

/// TypeScript for the whole protocol: message types, then one program per role.
pub fn typescript_stubs(protocol: &GlobalProtocol, schemas: &Schemas) -> Result<String, StubError> {
    let missing = schemas.missing(protocol);
    if !missing.is_empty() {
        return Err(StubError::MissingSchemas(missing));
    }
    let session = protocol.project().map_err(StubError::Protocol)?;

    let mut labels = Vec::new();
    collect_labels(protocol.statements(), &mut labels);

    let mut out = String::from(PREAMBLE);
    out.push('\n');
    for label in &labels {
        let schema = schemas.get(label).expect("missing schemas were rejected");
        out.push_str(&message_type(label, schema));
    }

    out.push_str("export type Messages = {\n");
    for label in &labels {
        let name = ident(label);
        out.push_str(&format!("  {name}: {name};\n"));
    }
    out.push_str("};\n");

    for program in session.programs() {
        let mut literal = String::new();
        action_list(&program.actions, &mut literal);
        out.push_str(&format!(
            "\nexport const {}Program: readonly Op[] = {literal} as const;\n",
            ident(&program.role)
        ));
    }
    Ok(out)
}

/// The types for one message: a named type for each definition, then the message itself.
fn message_type(label: &str, schema: &Value) -> String {
    let mut out = String::new();
    let defs = schema
        .get("$defs")
        .or_else(|| schema.get("definitions"))
        .and_then(Value::as_object);
    if let Some(defs) = defs {
        for (name, def) in defs {
            out.push_str(&format!(
                "export type {} = {};\n",
                def_name(label, name),
                ts(def, label)
            ));
        }
    }
    out.push_str(&format!(
        "export type {} = {};\n",
        ident(label),
        ts(schema, label)
    ));
    out
}

/// The TypeScript name of a definition inside a message's schema.
fn def_name(label: &str, name: &str) -> String {
    ident(&format!("{label}_{name}"))
}

/// The TypeScript type for a JSON Schema. Unsupported keywords become `unknown`.
fn ts(schema: &Value, label: &str) -> String {
    match schema {
        Value::Bool(true) => "unknown".into(),
        Value::Bool(false) => "never".into(),
        Value::Object(map) => {
            if let Some(reference) = map.get("$ref").and_then(Value::as_str) {
                let name = reference
                    .strip_prefix("#/$defs/")
                    .or_else(|| reference.strip_prefix("#/definitions/"));
                return name.map_or("unknown".into(), |name| def_name(label, name));
            }
            if let Some(constant) = map.get("const") {
                return literal(constant);
            }
            if let Some(values) = map.get("enum").and_then(Value::as_array) {
                return union(values.iter().map(literal));
            }
            for keyword in ["anyOf", "oneOf"] {
                if let Some(options) = map.get(keyword).and_then(Value::as_array) {
                    return union(options.iter().map(|option| ts(option, label)));
                }
            }
            match map.get("type") {
                Some(Value::String(kind)) => by_type(kind, map, label),
                Some(Value::Array(kinds)) => union(
                    kinds
                        .iter()
                        .filter_map(Value::as_str)
                        .map(|kind| by_type(kind, map, label)),
                ),
                _ if map.contains_key("properties") => object_type(map, label),
                _ => "unknown".into(),
            }
        }
        _ => "unknown".into(),
    }
}

fn by_type(kind: &str, map: &Map<String, Value>, label: &str) -> String {
    match kind {
        "string" => "string".into(),
        "integer" | "number" => "number".into(),
        "boolean" => "boolean".into(),
        "null" => "null".into(),
        "array" => match map.get("items") {
            Some(items) => format!("Array<{}>", ts(items, label)),
            None => "unknown[]".into(),
        },
        "object" => object_type(map, label),
        _ => "unknown".into(),
    }
}

fn object_type(map: &Map<String, Value>, label: &str) -> String {
    let required: Vec<&str> = map
        .get("required")
        .and_then(Value::as_array)
        .map(|names| names.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    match map.get("properties").and_then(Value::as_object) {
        Some(properties) if !properties.is_empty() => {
            let fields: Vec<String> = properties
                .iter()
                .map(|(name, schema)| {
                    let optional = if required.contains(&name.as_str()) {
                        ""
                    } else {
                        "?"
                    };
                    format!("{}{optional}: {}", property_name(name), ts(schema, label))
                })
                .collect();
            format!("{{ {} }}", fields.join("; "))
        }
        Some(_) => "{}".into(),
        None => match map.get("additionalProperties") {
            Some(extra @ Value::Object(_)) => format!("Record<string, {}>", ts(extra, label)),
            _ => "Record<string, unknown>".into(),
        },
    }
}

/// A union of distinct types, or `never` when there are none.
fn union(parts: impl Iterator<Item = String>) -> String {
    let mut unique: Vec<String> = Vec::new();
    for part in parts {
        if !unique.contains(&part) {
            unique.push(part);
        }
    }
    if unique.is_empty() {
        "never".into()
    } else {
        unique.join(" | ")
    }
}

/// A JSON value as a TypeScript literal type.
fn literal(value: &Value) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| "unknown".into())
}

/// A property key: bare when it is a plain identifier, quoted otherwise.
fn property_name(name: &str) -> String {
    let plain = !name.is_empty()
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !name.starts_with(|c: char| c.is_ascii_digit());
    if plain {
        name.to_string()
    } else {
        quoted(name)
    }
}

/// A name that is a valid TypeScript identifier.
fn ident(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

/// A string as a double-quoted TypeScript literal.
fn quoted(text: &str) -> String {
    serde_json::to_string(text).expect("a string serializes")
}

/// The program for a list of actions, as a TypeScript array literal.
fn action_list(actions: &[Action], out: &mut String) {
    out.push('[');
    for (index, action) in actions.iter().enumerate() {
        if index > 0 {
            out.push_str(", ");
        }
        action_value(action, out);
    }
    out.push(']');
}

fn action_value(action: &Action, out: &mut String) {
    match action {
        Action::Send { to, label } => out.push_str(&format!(
            "{{ op: \"send\", to: {}, label: {} }}",
            quoted(to),
            quoted(label)
        )),
        Action::Recv { from, label } => out.push_str(&format!(
            "{{ op: \"recv\", from: {}, label: {} }}",
            quoted(from),
            quoted(label)
        )),
        Action::Choose { to, branches } => {
            let roles: Vec<String> = to.iter().map(|role| quoted(role)).collect();
            out.push_str(&format!(
                "{{ op: \"choose\", to: [{}], branches: ",
                roles.join(", ")
            ));
            branch_list(branches, out);
            out.push_str(" }");
        }
        Action::Offer { from, branches } => {
            out.push_str(&format!(
                "{{ op: \"offer\", from: {}, branches: ",
                quoted(from)
            ));
            branch_list(branches, out);
            out.push_str(" }");
        }
        Action::Loop(body) => {
            out.push_str("{ op: \"loop\", body: ");
            action_list(body, out);
            out.push_str(" }");
        }
        Action::Continue => out.push_str("{ op: \"continue\" }"),
    }
}

fn branch_list(branches: &[Vec<Action>], out: &mut String) {
    out.push('[');
    for (index, branch) in branches.iter().enumerate() {
        if index > 0 {
            out.push_str(", ");
        }
        action_list(branch, out);
    }
    out.push(']');
}
